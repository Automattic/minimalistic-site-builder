     * -------------------------------------------------------------------
     * Plumbing
     * -------------------------------------------------------------------
     */

    /**
     * Agent hints for a registry entry, defaults filled in.
     *
     * This trimmed manifest never emits agent_hints, so the defaults apply
     * and the W_HINT_* checks never fire; the helper is kept for fidelity.
     *
     * @param array $type Registry entry.
     * @return array
     */
    private static function hints_of( array $type ): array {
        $defaults = array(
            'allowed_blocks'     => null,
            'template_lock'      => null,
            'usage_notes'        => '',
            'example_attributes' => array(),
        );

        $hints = $type['agent_hints'] ?? array();
        if ( $hints instanceof stdClass ) {
            $hints = (array) $hints;
        }

        return array_merge( $defaults, is_array( $hints ) ? $hints : array() );
    }

    /**
     * True when a decoded value stands for a JSON object.
     *
     * A body decoded with objects preserved gives stdClass for every JSON
     * object, so the test is exact there. Associative arrays are accepted too;
     * the one residual ambiguity is an empty PHP array, which is treated as
     * an empty object.
     *
     * @param mixed $value Value.
     * @return bool
     */
    private static function is_json_object( $value ): bool {
        if ( $value instanceof stdClass ) {
            return true;
        }

        return is_array( $value ) && ( array() === $value || ! array_is_list( $value ) );
    }

    /**
     * True when a decoded value stands for a JSON array.
     *
     * stdClass never qualifies, so `"innerBlocks": {}` is a schema error.
     *
     * @param mixed $value Value.
     * @return bool
     */
    private static function is_json_array( $value ): bool {
        return is_array( $value ) && array_is_list( $value );
    }

    /**
     * Decoded JSON object as an associative array.
     *
     * @param mixed $value Value.
     * @return array
     */
    private static function to_map( $value ): array {
        if ( $value instanceof stdClass ) {
            return (array) $value;
        }

        return is_array( $value ) ? $value : array();
    }

    /**
     * RFC 6901 token escaping: ~ -> ~0, / -> ~1.
     *
     * @param string $token Raw token.
     * @return string
     */
    public static function escape_pointer_token( string $token ): string {
        return str_replace( array( '~', '/' ), array( '~0', '~1' ), $token );
    }

    /**
     * Build a diagnostic.
     *
     * @param string      $code     Diagnostic code.
     * @param string      $severity error|warning.
     * @param string      $path     RFC 6901 pointer.
     * @param string      $message  Human text.
     * @param string|null $fix_hint Optional hint.
     * @return array
     */
    private static function make( string $code, string $severity, string $path, string $message, ?string $fix_hint = null ): array {
        $diagnostic = array(
            'code'     => $code,
            'severity' => $severity,
            'path'     => $path,
            'message'  => $message,
        );

        if ( null !== $fix_hint ) {
            $diagnostic['fix_hint'] = $fix_hint;
        }

        return $diagnostic;
    }

    /**
     * Append a diagnostic to the current run.
     *
     * @param string      $code     Diagnostic code.
     * @param string      $severity error|warning.
     * @param string      $path     RFC 6901 pointer.
     * @param string      $message  Human text.
     * @param string|null $fix_hint Optional hint.
     * @return void
     */
    private static function add( string $code, string $severity, string $path, string $message, ?string $fix_hint = null ): void {
        self::$diagnostics[] = self::make( $code, $severity, $path, $message, $fix_hint );
    }

    /**
     * Assemble the Diagnostics document.
     *
     * @param array  $diagnostics        Diagnostics.
     * @param bool   $epoch_ok           Epoch comparison result.
     * @param string $server_fingerprint Current epoch.
     * @return array
     */
    private static function document( array $diagnostics, bool $epoch_ok, string $server_fingerprint ): array {
        $valid = true;
        foreach ( $diagnostics as $diagnostic ) {
            if ( 'error' === $diagnostic['severity'] ) {
                $valid = false;
                break;
            }
        }

        return array(
            'valid'              => $valid,
            'epoch_ok'           => $epoch_ok,
            'server_fingerprint' => $server_fingerprint,
            'diagnostics'        => array_values( $diagnostics ),
        );
    }
