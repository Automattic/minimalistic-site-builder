#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');
const {
  REPOSITORY_ROOT,
  createOracleFingerprint,
  sha256,
  sha256File,
} = require('./block-fixer/lib/oracleFingerprint');
const { installDomEnvironment } = require('./block-fixer/lib/domEnvironment');
const {
  installOracleInstrumentation,
} = require('./block-fixer/lib/oracleInstrumentation');
const {
  assertSupportedManifestMatches,
  buildRegistrySnapshot,
} = require('./block-fixer/lib/registrySnapshot');

const GENERATOR_VERSION = '1.0.0';
const EXPECTED_REGISTERED_COUNT = 106;
const FIXTURES_ROOT = path.join(REPOSITORY_ROOT, 'tests', 'fixtures', 'block-fixer');
const RUNTIME_JSON = path.join(FIXTURES_ROOT, 'registered-runtime.json');
const ORACLE_MANIFEST = path.join(FIXTURES_ROOT, 'oracle-manifest.json');
const PHP_REGISTRY = path.join(
  REPOSITORY_ROOT,
  'src',
  'BlockSerializer',
  'Registry',
  'generated-registry.php'
);
const PHP_SUPPORT_MANIFEST = path.join(
  REPOSITORY_ROOT,
  'src',
  'BlockSerializer',
  'Registry',
  'supported-blocks.php'
);

function stableJson(value) {
  return JSON.stringify(value, null, 2) + '\n';
}

function phpString(value) {
  return `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;
}

function phpExport(value, depth = 0) {
  const indent = '    '.repeat(depth);
  const childIndent = '    '.repeat(depth + 1);
  if (value === null) return 'null';
  if (value === true) return 'true';
  if (value === false) return 'false';
  if (typeof value === 'string') return phpString(value);
  if (typeof value === 'number') {
    if (Object.is(value, -0)) return '-0.0';
    return String(value);
  }
  if (Array.isArray(value)) {
    if (value.length === 0) return '[]';
    return '[\n'
      + value.map((item) => `${childIndent}${phpExport(item, depth + 1)},`).join('\n')
      + `\n${indent}]`;
  }
  if (typeof value === 'object') {
    const entries = Object.entries(value);
    if (entries.length === 0) return '[]';
    return '[\n'
      + entries.map(([key, item]) => (
        `${childIndent}${phpString(key)} => ${phpExport(item, depth + 1)},`
      )).join('\n')
      + `\n${indent}]`;
  }
  throw new TypeError(`Cannot export ${typeof value} to PHP`);
}

function phpRegistry(snapshot, fingerprint) {
  const payload = {
    metadata: {
      schemaVersion: 1,
      generatorVersion: GENERATOR_VERSION,
      packageLockSha256: fingerprint.packageLockSha256,
      node: fingerprint.node,
      counts: snapshot.counts,
      hookTrace: snapshot.hookTrace,
    },
    registered: snapshot.registered,
    supported: snapshot.supported,
    observed: snapshot.observed,
  };
  return `<?php\n`
    + `declare(strict_types=1);\n\n`
    + `// Generated by bin/generate-block-registry.js ${GENERATOR_VERSION}.\n`
    + `// Regenerate explicitly with --update; do not edit by hand.\n`
    + `return ${phpExport(payload)};\n`;
}

function assertOrWrite(file, content, update) {
  if (update) {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
    return;
  }
  if (!fs.existsSync(file)) {
    throw new Error(`Missing generated artifact ${path.relative(REPOSITORY_ROOT, file)}; run with --update`);
  }
  const existing = fs.readFileSync(file, 'utf8');
  if (existing !== content) {
    throw new Error(`Generated artifact drift in ${path.relative(REPOSITORY_ROOT, file)}; review an explicit --update`);
  }
}

function prepareRuntime() {
  installDomEnvironment({ forwardJsdomErrors: false });
  installOracleInstrumentation();
  const noop = () => {};
  for (const method of [
    'log', 'info', 'warn', 'debug', 'dir', 'trace', 'error',
    'group', 'groupCollapsed', 'groupEnd',
  ]) {
    console[method] = noop;
  }
  require('./block-fixer/lib/blockFixer').initializeBlockRegistry({ throwOnError: true });
}

function generate() {
  assertSupportedManifestMatches(PHP_SUPPORT_MANIFEST);
  prepareRuntime();
  const fingerprint = createOracleFingerprint();
  const snapshot = buildRegistrySnapshot(FIXTURES_ROOT);
  if (snapshot.counts.registered !== EXPECTED_REGISTERED_COUNT) {
    throw new Error(
      `Registered universe drift: expected ${EXPECTED_REGISTERED_COUNT}, got ${snapshot.counts.registered}`
    );
  }
  const runtime = {
    generator: {
      version: GENERATOR_VERSION,
      sourceSha256: sha256File(__filename),
    },
    fingerprint,
    ...snapshot,
  };
  const runtimeContent = stableJson(runtime);
  const phpContent = phpRegistry(snapshot, fingerprint);
  const fixtureGenerator = path.join(REPOSITORY_ROOT, 'bin', 'generate-block-fixer-fixtures.js');
  const fixtureCases = path.join(
    REPOSITORY_ROOT,
    'bin',
    'block-fixer',
    'lib',
    'fixtureCases.js'
  );
  const manifest = {
    schemaVersion: 1,
    fingerprint,
    registry: {
      generatorVersion: GENERATOR_VERSION,
      generatorSourceSha256: sha256File(__filename),
      runtimeJsonSha256: sha256(runtimeContent),
      generatedPhpSha256: sha256(phpContent),
      registeredSnapshotSha256: sha256(stableJson(snapshot.registered)),
      hookTraceSha256: sha256(stableJson(snapshot.hookTrace)),
      counts: snapshot.counts,
    },
    fixtures: {
      generatorVersion: fs.existsSync(fixtureGenerator)
        ? require(fixtureGenerator).GENERATOR_VERSION
        : null,
      generatorSourceSha256: fs.existsSync(fixtureGenerator)
        ? sha256File(fixtureGenerator)
        : null,
      definitionsSha256: sha256File(fixtureCases),
    },
  };
  return {
    runtimeContent,
    phpContent,
    manifestContent: stableJson(manifest),
    snapshot,
  };
}

function main(argv = process.argv.slice(2)) {
  const unknown = argv.filter((argument) => argument !== '--update');
  if (unknown.length > 0) {
    process.stderr.write(`Unknown argument(s): ${unknown.join(', ')}\n`);
    return 2;
  }
  const update = argv.includes('--update');
  try {
    const generated = generate();
    assertOrWrite(RUNTIME_JSON, generated.runtimeContent, update);
    assertOrWrite(PHP_REGISTRY, generated.phpContent, update);
    assertOrWrite(ORACLE_MANIFEST, generated.manifestContent, update);
    process.stdout.write(
      `[block-registry] ${update ? 'updated' : 'verified'} `
      + `${generated.snapshot.counts.registered} registered, `
      + `${generated.snapshot.counts.supported} supported, `
      + `${generated.snapshot.counts.observed} observed block name(s).\n`
    );
    return 0;
  } catch (error) {
    process.stderr.write(`[block-registry] ${error.stack || error.message}\n`);
    return 1;
  }
}

if (require.main === module) {
  process.exitCode = main();
}

module.exports = {
  EXPECTED_REGISTERED_COUNT,
  GENERATOR_VERSION,
  generate,
  main,
  phpExport,
};
